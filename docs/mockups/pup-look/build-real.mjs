// Bundles the REAL game art code (unchanged) into a classic script for the file:// sandbox:
//   src/gfx/wrenart.js + eliasart.js (heroes, real helpers), src/gfx/husk/* (real Husk enemies as SVG strings).
// node build-real.mjs [repoDir]  -> real-rigs.js (window.RIGS = {wren, elias}, window.HUSKS = {...})
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createRequire } from 'node:module';
const repo = (process.argv[2] || 'C:/Users/matty/spirit-pupart').split(String.fromCharCode(92)).join('/');
const require = createRequire(join(repo, 'package.json'));
const esbuild = require('esbuild');
const g = (f) => JSON.stringify(`${repo}/src/gfx/${f}`);
const entry = `import * as wren from ${g('wrenart.js')}; import * as elias from ${g('eliasart.js')};
import { HUSK_TYPES, wpd } from ${g('husk/frames.js')}; import { resetAll, defs, setGrainBox, setEyeSpecies, clearEyes } from ${g('husk/paint.js')}; import { EXTRA_DEFS } from ${g('husk/kit.js')};
window.RIGS = { wren, elias };
// one Husk frame as a standalone SVG (same steps as frames.js typeSheet: baked eyes, frame box), plus its world-units-per-du
window.HUSKS = { ids: Object.keys(HUSK_TYPES), svg(id, st) { const T = HUSK_TYPES[id]; resetAll(); setEyeSpecies(id); setGrainBox(...T.box); clearEyes();
  const r = T.fn(st); const b = T.box; return { svg: '<svg xmlns="http://www.w3.org/2000/svg" width="' + b[2] + '" height="' + b[3] + '" viewBox="' + b.join(' ') + '">' + defs() + '<defs>' + EXTRA_DEFS + '</defs>' + r.b + r.e + '</svg>', box: b, wpd: wpd(id), foot: T.foot }; } };`;
const r = await esbuild.build({ stdin: { contents: entry, resolveDir: repo, sourcefile: 'entry.js' }, bundle: true, format: 'iife', write: false, platform: 'browser', target: 'es2020', legalComments: 'none' });
const out = `// GENERATED by build-real.mjs from ${repo}/src/gfx (unchanged game code; do not edit)\n` + r.outputFiles[0].text;
writeFileSync(new URL('./real-rigs.js', import.meta.url), out);
console.log('real-rigs.js', out.length, 'chars');
