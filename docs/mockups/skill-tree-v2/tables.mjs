// Prints the markdown tables used in docs/design/skill-tree-v2.md (inventory, id mapping, budget, economy).
// node docs/mockups/skill-tree-v2/tables.mjs > out.md
import { readFileSync } from 'node:fs';
import { buildList, CAPS, softTotal, CLUSTERS, GATE_RUNS } from './inventory.mjs';
const v1 = JSON.parse(readFileSync(new URL('../../../src/data/tree.json', import.meta.url), 'utf8')).nodes;
const L = buildList();
const real = L.filter((n) => !n.display);
const ids = new Set(real.map((n) => n.id));
const missing = v1.filter((n) => !ids.has(n.id)).map((n) => n.id);
const dup = real.map((n) => n.id).filter((x, i, a) => a.indexOf(x) !== i);
const out = [];
const p = (s) => out.push(s);
p(`<!-- generated by docs/mockups/skill-tree-v2/tables.mjs -->`);
p(`v1 ids: ${v1.length}; v2 real nodes: ${real.length} (kept v1 ids ${real.filter((n) => n.v1).length}, new ${real.filter((n) => !n.v1).length}); display-only (starter hearts/sockets): ${L.length - real.length}; v1 ids missing in v2: ${missing.length ? missing.join(', ') : 'none'}; duplicate ids: ${dup.length ? dup.join(', ') : 'none'}`);
p('');
// counts
const by = (f) => { const m = {}; for (const n of real) { const k = f(n); m[k] = (m[k] || 0) + 1; } return m; };
p('| Region | Nodes (buyable incl. gates) | of which NEW ids | kinds |');
p('|---|---|---|---|');
for (const wid of Object.keys(CLUSTERS)) {
  const ns = real.filter((n) => n.cluster === wid && n.kind !== 'hero');
  const k = {}; ns.forEach((n) => { k[n.kind] = (k[n.kind] || 0) + 1; });
  p(`| ${CLUSTERS[wid].name} constellation | ${ns.length} (+${L.filter((n) => n.display && n.cluster === wid).length} display) | ${ns.filter((n) => !n.v1).length} | ${Object.entries(k).map(([a, b]) => `${a} ${b}`).join(', ')} |`);
}
for (const r of ['hearth', 'wick', 'dusk', 'fog']) { const ns = real.filter((n) => n.ring === r); p(`| ${r} ring | ${ns.length} | ${ns.filter((n) => !n.v1).length} | ${[...new Set(ns.map((n) => n.kind))].join(', ')} |`); }
for (const h of ['wren', 'elias']) { const ns = real.filter((n) => n.hero === h); p(`| ${h} hero lantern | ${ns.length} | ${ns.filter((n) => !n.v1).length} | hero |`); }
p(`| **Total** | **${real.length}** | **${real.filter((n) => !n.v1).length}** | |`);
p('');
// budget
const S = {}; const add = (k, v) => { S[k] = (S[k] || 0) + v; };
const keySkip = new Set(['ma_key', 'li_glass']); // exclusive pairs: count the better side once (su_key, li_lantern counted as the larger in their category)
let sustain = 0.6; // rerolls 3 + banishes 3 at 0.1 PE each (ablation: removing all six moved the bot 0-4 win points)
for (const n of real) {
  if (keySkip.has(n.id)) continue;
  if (n.cat.startsWith('wpn:')) add(n.cat, n.face);
  else if (CAPS[n.cat]) add(n.cat, n.face);
  else if (n.cat === 'sustain') sustain += n.id === 'li_last' ? 4.0 : n.id === 'li_hearts' ? n.face * 0.04 : n.id === 'li_heal' ? n.face * 0.04 : n.face;
}
p('| Category | Cap C (stat %) | Weight | Face sum S | Soft total C(1-e^(-S/C)) | PE at total | PE at cap |');
p('|---|---|---|---|---|---|---|');
let pe = 0, peCap = 0;
for (const [k, c] of Object.entries(CAPS)) {
  if (k === 'wpn') {
    let s = 0, t = 0;
    for (const wid of Object.keys(CLUSTERS)) { const sw = S[`wpn:${wid}`] || 0; s += sw; t += softTotal(sw, c.C); }
    const ppe = t * c.w; pe += ppe; peCap += c.C * 5 * c.w;
    p(`| ${c.label} | ${c.C} each | ${c.w} | ${s.toFixed(1)} (${Object.keys(CLUSTERS).map((w) => (S[`wpn:${w}`] || 0).toFixed(0)).join('/')}) | ${t.toFixed(1)} (sum of 5) | ${ppe.toFixed(2)} | ${(c.C * 5 * c.w).toFixed(2)} |`);
    continue;
  }
  const s = S[k] || 0; const t = softTotal(s, c.C); pe += t * c.w; peCap += c.C * c.w;
  p(`| ${c.label} | ${c.C} | ${c.w} | ${s.toFixed(1)} | ${t.toFixed(2)} | ${(t * c.w).toFixed(2)} | ${(c.C * c.w).toFixed(2)} |`);
}
p(`| **Combat total** | | | | | **${pe.toFixed(2)}** | **${peCap.toFixed(2)}** (validator limit 15.5) |`);
p(`| Sustain/verb (fixed values: revive 4.0, rerolls+banishes 6 x 0.1, hearts 0.04/%, heart heal 0.04/%) | | | | | **${sustain.toFixed(2)}** | ceiling 5 |`);
p('');
// economy
let g = 0, sh = 0, gGate = 0;
for (const n of real) { if (n.kind === 'teaser') continue; g += n.gold; sh += n.shards || 0; if (n.kind === 'heart' || n.kind === 'socket') gGate += n.gold; }
p(`Economy: total ${g} gold + ${sh} soul shards (gates/sockets ${gGate} gold). At ~1800 gold per bot run that is ~${Math.round(g / 1800)} runs; at a casual ~1300 gold ~${Math.round(g / 1300)} runs. v1 was 58,430 gold + 25 shards.`);
p('');
// mapping table
p('| id | v1 or NEW | v2 place | kind | v2 effect (per node) | gold | shards | unlock condition |');
p('|---|---|---|---|---|---|---|---|');
const cond = (c) => { if (!c) return ''; if (typeof c === 'string') return c; if (c.t === 'any' || c.t === 'all') return c.of.map(cond).join(c.t === 'any' ? ' OR ' : ' AND '); return `${c.t} ${c.id || c.chapter || ''} ${c.n || c.seconds || ''}`.replace(/\s+/g, ' ').trim(); };
for (const n of L) {
  const place = n.cluster ? (n.hero ? `${n.hero} lantern` : `${CLUSTERS[n.cluster].name}${n.slot ? ` / ${n.slot}` : n.point ? ` / ${n.point}` : ' / heart'}`) : `${n.ring} ring`;
  p(`| ${n.id} | ${n.display ? 'display' : n.v1 ? 'v1' : 'NEW'} | ${place} | ${n.kind} | ${n.text}${n.excl ? ` (excludes ${n.excl})` : ''} | ${n.gold} | ${n.shards || 0} | ${cond(n.unlock || n.cond)}${GATE_RUNS[n.id] ? ` (bot runs: ${GATE_RUNS[n.id]})` : ''} |`);
}
console.log(out.join('\n'));
